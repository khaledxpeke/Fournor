export function applyI18n(lang = getLang()) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder, lang));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria, lang));
  });
  const meta = document.querySelector("title[data-i18n], title");
  const page = document.body?.dataset.page;
  const titleKey = page ? `meta.${page}` : "meta.home";
  if (meta) document.title = t(titleKey, lang);
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  window.dispatchEvent(new CustomEvent("fournor:lang", { detail: lang }));
}
