const KEY = "fournor-lang";
const LANGS = ["fr", "en", "ar"];

export function isRtl(lang = getLang()) {
  return lang === "ar";
}

export function getLang() {
  const saved = localStorage.getItem(KEY);
  if (LANGS.includes(saved)) return saved;
  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("ar")) return "ar";
  if (nav.startsWith("en")) return "en";
  return "fr";
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  localStorage.setItem(KEY, lang);
  applyI18n(lang);
}

export function t(key, lang = getLang()) {
  return dict[lang]?.[key] ?? dict.fr[key] ?? key;
}

export function applyI18n(lang = getLang()) {
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl(lang) ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder, lang));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria, lang));
  });
  const meta = document.querySelector("title[data-i18n], title");
  const page = document.body?.dataset.page;
  const titleKey = page ? `meta.${page}` : "meta.home";
  if (meta) document.title = t(titleKey, lang);
  const desc = document.querySelector("meta[name='description']");
  if (desc && page) desc.setAttribute("content", t(`meta.desc.${page}`, lang));
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  window.dispatchEvent(new CustomEvent("fournor:lang", { detail: lang }));
}
